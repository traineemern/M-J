export function resolveContent<T>(field: Tagged<T>): T | undefined {
  const environment = import.meta.env
  const samplesEnabled = environment?.DEV && environment.VITE_SHOW_SAMPLE_DATA === 'true'
  if (field.source === 'dummy' && !samplesEnabled) return undefined
  return field.value
}

export function addressText(): string {
  const { address } = siteContent.business
  return `${resolveContent(address.street)}, ${resolveContent(address.city)}, ${resolveContent(address.state)} ${resolveContent(address.zip)}`
}

